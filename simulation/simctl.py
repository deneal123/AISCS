"""Bounded, sequential Linux-Docker evaluations of pinned sidecars.

Source trees are read-only inputs. Every generated byte belongs in research/.work.
The admission check is also used while a container is running; only the container
created by this invocation can be stopped. No scientific claims follow from exit 0.
"""

from __future__ import annotations

