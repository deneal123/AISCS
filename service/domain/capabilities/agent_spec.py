"""Декларация субагента: всё, что о нём знает остальная система.

⚠️ ЗАЧЕМ. Знание об агенте жило в девяти независимых литеральных списках: фабрика,
`ALLOWED_CATEGORIES`, `_ALLOWED_FORCED_CATEGORIES`, `_VALID_TOOLS`, `_ROUTE_LABELS`,
категории в `_DECOMPOSE_PROMPT`, блок маршрутов в `AUTO_PROMPT`, `BILLABLE_TOOLS` и разбор
`auto_tool` в use-case. Пропуск любого НЕ давал ни ошибки, ни лога: агент просто выпадал из
мульти-интента, показывался в трейсе машинным именем или не тарифицировался.

Приём скопирован с `ProviderSpec` (`domain/client/providers/spec.py`), где он уже доказан:
провайдер добавляется двумя файлами, и это держит тест, объявляющий фиктивного провайдера
целиком внутри себя.

⚠️ Настройки адресуются ИМЕНЕМ поля, а не читаются на импорте — иначе спека замкнула бы
модуль настроек на домен и запомнила бы окружение момента импорта.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from typing import Any

# Классы цены. Определяют, насколько охотно оркестратор вправе включать режим сам:
# дешёвое — свободно, платное — по явным признакам, дорогое — только по кнопке человека.
COST_CHEAP = "cheap"
COST_PAID = "paid"
COST_EXPENSIVE = "expensive"
COST_CLASSES = (COST_CHEAP, COST_PAID, COST_EXPENSIVE)


@dataclass(frozen=True, slots=True)
class AgentSpec:
    """Одна декларация субагента. Всё производное выводится отсюда."""

    name: str
    label_ru: str
    build: Callable[[dict], Any]

    # --- маршрутизация ---------------------------------------------------- #
    # Может ли модель-роутер ВЫБРАТЬ этот маршрут сама. `audio_transcribe` — нет:
    # он форсится типом вложения, а угаданный по тексту уводил «вот файл» с .md на ASR.
    routable: bool = True
    # Может ли человек потребовать этот режим тумблером.
    forceable: bool = True
    # Может ли агент быть ШАГОМ мульти-интента. Забытый здесь молча выпадал из разбора.
    decomposable: bool = True
    # Модальность, без которой маршрут недопустим (защита в глубину, три копии до этого).
    requires_input_type: str | None = None
    # Модальности, которые форсят этот маршрут сами по себе.
    forced_by_input_type: tuple[str, ...] = ()
    # ⚠️ Побеждает ли модальность ТУМБЛЕР человека. Голосовое сообщение — факт, и оно
    # сильнее переключателя; загруженная картинка — тоже факт, но человек вправе
    # потребовать по ней ресёрч, поэтому её правило стоит НИЖЕ флагов. Порядок здесь не
    # косметика: перепутав его, «включил deep research и приложил картинку» отвечало бы
    # обычным ответом.
    input_type_beats_toggles: bool = False

    # --- деньги ------------------------------------------------------------ #
    # Имя в `contracts.BILLABLE_TOOLS`. `None` — надбавки нет (обычный ответ).
    billing_name: str | None = None
    cost_class: str = COST_CHEAP
    # Дорогой режим оркестратор не запускает сам: отвечает обычным и предлагает кнопкой.
    confirm_by_default: bool = False

    # --- промпты ----------------------------------------------------------- #
    # Строка для генерируемого блока маршрутов в `AUTO_PROMPT`: текст ПОСЛЕ «— »,
    # включая перенос и отступ продолжения. Пусто — маршрут в промпт не попадает.
    prompt_hint: str = ""

    # --- доступность ------------------------------------------------------- #
    # Имя булева поля `AgentsConfig`, выключающего агента. Проверяется тестом на
    # существование: опечатка здесь тихая — `getattr(..., None)` даст «выключен».
    enabled_field: str | None = None

    def __post_init__(self) -> None:
        if self.cost_class not in COST_CLASSES:
            raise ValueError(f"{self.name}: неизвестный класс цены {self.cost_class!r}")
