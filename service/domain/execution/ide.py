def ide_instructions() -> str:
    from service.domain.execution.context import current_execution

    execution = current_execution()
    if not execution or not execution.policy.flag("ide_tools_enabled"):
        return ""
    commands = execution.policy.flag("ide_command_tools_enabled")
    return IDE_INSTRUCTIONS + (
        " После правки используй ide_run_command для проверки verify_project. "
        "Не заменяй неуспешный рецепт другим. Допускаются два исправления в общем бюджете. "
        "Не утверждай готовность без подтверждённой проверки."
        if commands
        else " Команды недоступны: ничего не запускай; проверку обозначь заблокированной."
    )
