"""Ссылки, которые агент ПРОЧИТАЛ за прогон, — чтобы они пережили ход диалога.

🔴 Живой кейс: ассистент нашёл вакансию (Tripster, HH.ru) и ответил по ней, а на
следующий вопрос «что можешь по ней сказать» ответил, что описания НЕ ВИДИТ, и попросил
прислать ссылку. В историю треда уезжает только текст ответа; результат инструмента —
самая дорогая часть хода — исчезает вместе с раундом. Пользователь при этом видит связный
разговор и не понимает, почему собеседник забыл то, что сам же нашёл минуту назад.

⚠️ ПОЧЕМУ ЧЕРЕЗ ContextVar, А НЕ ЧЕРЕЗ `ctx`. Инструмент получает `RunContextWrapper`, но
внутри него — `model_dump()` контекста, то есть ПЛОСКАЯ КОПИЯ: дописать в неё можно, а
вызывающий этого не увидит. Тянуть же сборщик аргументом пришлось бы через цикл
инструментов и полтора десятка сигнатур — ровно тот довод, по которому через ContextVar
уже переданы личность, потолок токенов и дедлайн.

⚠️ В переменной лежит СПИСОК, и это важно: раунд инструментов исполняется в дочерних
задачах (`asyncio.gather`), а они получают КОПИЮ контекста — присваивание из дочерней
задачи наверх не вернулось бы. Ссылка на общий список возвращается, дозапись в него видна
всем.

Форма записи — `{url, title, ok}`, ровно та, которую уже рисует `MessageSources` во
фронте: новый вид у одного и того же по смыслу списка означал бы вторую разметку и вторую
причину чинить.
"""

from __future__ import annotations

from contextlib import contextmanager
from contextvars import ContextVar

# Потолок на прогон: список уезжает и в метаданные сообщения, и в историю следующего хода.
# Без него длинный поисковый диалог однажды начнёт возить в промпте десятки ссылок.
MAX_SOURCES = 12
MAX_TITLE_CHARS = 120

_CURRENT: ContextVar[list[dict] | None] = ContextVar("gpthub_found_sources", default=None)


@contextmanager
def collect():
    """Включить сбор на время прогона. Отдаёт список, который потом уедет в metadata."""
    sources: list[dict] = []
    token = _CURRENT.set(sources)
    try:
        yield sources
    finally:
        _CURRENT.reset(token)


def remember(items) -> None:
    """Запомнить прочитанные ссылки. Вне прогона — молча ничего.

    Дедуп по адресу: один и тот же источник модель нередко находит несколькими запросами,
    и трижды показанная ссылка в чипах выглядит как три разных источника.
    """
    sources = _CURRENT.get()
    if sources is None:
        return
    known = {str(s.get("url") or "") for s in sources}
    for item in items or ():
        url = str((item or {}).get("url") or "").strip()
        if not url or url in known or len(sources) >= MAX_SOURCES:
            continue
        known.add(url)
        sources.append(
            {
                "url": url,
                "title": str((item or {}).get("title") or "").strip()[:MAX_TITLE_CHARS],
                "ok": True,
            }
        )


def collected() -> list[dict]:
    """Что собрано за прогон. Пусто — инструмент не звался или сбор не включён."""
    return list(_CURRENT.get() or ())
