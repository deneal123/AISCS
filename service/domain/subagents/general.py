class GeneralAgent(SimpleStreamingAgent):
    """Universal assistant used for standard requests."""

    # Стилевые строки базового промпта уступают личности (см. PERSONA_OVERRIDES).
    persona_overrides = PERSONA_OVERRIDES

    def __init__(self, model_settings: dict):
        super().__init__(
            name="general",
            instructions=GENERAL_PROMPT,
            model_settings=model_settings,
            tools=DEFAULT_FUNCTION_TOOLS,
            input_guardrails=[
                check_appropriate_language,
                check_forbidden_topics,
            ],
            output_guardrails=[
                ensure_non_empty_response,
                fact_check_output,
                validate_response_relevance,
            ],
            # ⚠️ 4, А НЕ 8. Каждый tool-раунд — отдельный вызов LLM, и он переотправляет
            # ВЕСЬ растущий диалог (реплики с tool_calls + результаты). 8 раундов = до 9
            # вызовов, каждый с полной базой промпта — квадратичный рост стоимости. Для
            # анализа данных / поиска 4 раундов достаточно; сложное разбивается на шаги
            # мульти-интентом, а не циклом инструментов. Прежнее значение и дало prompt
            # 89 537 токенов на анализ 22 строк.
            max_turns=4,
        )


SPEC = AgentSpec(
    name="general",
    label_ru="обычный ответ",
    build=GeneralAgent,
    # ⚠️ Загруженная КАРТИНКА означает анализ, а не генерацию — но правило стоит
    # НИЖЕ тумблеров: человек вправе потребовать по ней ресёрч.
    forced_by_input_type=("image",),
    prompt_hint=(
        "обычный ответ. Сюда же анализ приложенных файлов, кода, таблиц, объяснения,\n"
        "  советы, тексты. ВЫБОР ПО УМОЛЧАНИЮ: при сомнении ставь general."
    ),
)
