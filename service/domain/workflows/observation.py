"""Какие цепочки шагов повторяются в треде — и стоит ли предлагать их закрепить.

🔴 ЗАЧЕМ. `WorkflowSpec` — это ДАННЫЕ, а не код: `instantiate()` отдаёт обычный
`list[SubTask]`, значит сочинить спеку может не только человек. Первый шаг к этому —
ЗАМЕТИТЬ повтор: если в треде трижды подряд разбирается одна и та же последовательность
категорий, декомпозиция каждый раз платит вызовом модели за один и тот же ответ.

⚠️ ПРАВИЛО ЗДЕСЬ, ХРАНЕНИЕ — СНАРУЖИ. Модуль ничего не знает про Redis и получает историю
списком: решение «повтор или совпадение» проверяется без сети, а значит проверяется вообще.
Ровно та же причина, по которой отбор кадров у сайдкара просмотра живёт отдельно от ffmpeg.

⚠️ ЭТО ТОЛЬКО НАБЛЮДЕНИЕ. Ни спеки, ни запуска здесь нет: автосборка НЕ означает
автозапуск, и сочинённый workflow обязан пройти те же ворота стоимости, что объявленный.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass

# Сколько раз цепочка должна повториться, чтобы считаться сценарием, а не совпадением.
# ⚠️ Два — мало: две одинаковые пары шагов подряд случаются у любого, кто дважды
# переформулировал вопрос. Три — уже привычка.
MIN_REPEATS = 3
# Ниже двух шагов «цепочки» нет: один шаг — это обычный ответ, и закреплять в нём нечего.
MIN_STEPS = 2
# Потолок длины наблюдаемой истории. Тред живёт долго, а решение принимается по недавнему:
# сценарий полугодовой давности к сегодняшней работе отношения не имеет.
MAX_HISTORY = 40


@dataclass(frozen=True, slots=True)
class Chain:
    """Одна исполненная последовательность: категории шагов по порядку."""

    steps: tuple[str, ...]
    # 🔴 ОТКУДА ОНА ВЗЯЛАСЬ. Цепочку, развёрнутую из УЖЕ ОБЪЯВЛЕННОГО workflow, наблюдать
    # нельзя: она повторяется по построению, и мы предложили бы закрепить то, что уже
    # закреплено, — бесконечно. Признак ставит вызывающий, а не догадка по форме.
    from_workflow: bool = False
    # Хоть один шаг упал. Неудачную цепочку предлагать нельзя: закрепив её, мы сделали бы
    # детерминированным повторение ошибки.
    failed: bool = False

    def key(self) -> str:
        return " → ".join(self.steps)


def observe(history: list[Chain], chain: Chain) -> list[Chain]:
    """Дописать наблюдение к истории треда, отбросив то, что наблюдать не следует.

    Отбрасываем ЗДЕСЬ, а не при разборе: иначе история копила бы мусор, а правило повтора
    считало бы по нему — и «трижды» набиралось бы из провалов и раскрытых workflow.
    """
    if chain.from_workflow or chain.failed or len(chain.steps) < MIN_STEPS:
        return list(history)[-MAX_HISTORY:]
    return [*history, chain][-MAX_HISTORY:]


def repeating(history: list[Chain], min_repeats: int = MIN_REPEATS) -> Chain | None:
    """Цепочка, повторившаяся достаточно, чтобы предложить её закрепить. `None` — нет такой.

    ⚠️ САМАЯ ЧАСТАЯ, а не самая длинная и не последняя: длинная выигрывала бы у полезной
    просто размером, а последняя предлагала бы то, что человек делает прямо сейчас, — то
    есть в момент, когда предложение мешает больше всего.

    ⚠️ При равенстве частот берём ту, что встретилась РАНЬШЕ: иначе порядок предложений
    зависел бы от порядка словаря, и одна и та же история давала бы разные ответы.
    """
    counts = Counter(item.key() for item in history)
    order = {item.key(): index for index, item in reversed(list(enumerate(history)))}
    best = None
    for key, count in counts.items():
        if count < min_repeats:
            continue
        if best is None or (count, -order[key]) > (best[1], -order[best[0]]):
            best = (key, count)
    if best is None:
        return None
    return next(item for item in history if item.key() == best[0])


def already_declared(chain: Chain, declared: set[str]) -> bool:
    """Такая последовательность уже объявлена спекой — предлагать нечего.

    🔴 Сверяем по СОСТАВУ ШАГОВ, а не по имени: сочинённая цепочка имени не имеет, а
    объявленный workflow с тем же составом делает ровно то же самое. Без этой проверки
    платформа предлагала бы закрепить то, что у неё уже есть.
    """
    return chain.key() in declared
