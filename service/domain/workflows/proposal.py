"""Предложение закрепить замеченный сценарий — кандидатом, а не втихую.

🔴 ПРЕДЛОЖЕНИЕ, А НЕ ЗАКРЕПЛЕНИЕ. Платформа заметила повтор — это ещё не значит, что она
права: три одинаковых разбора могли быть тремя попытками добиться толка. Решает человек, и
до его нажатия ничего не меняется.

⚠️ АВТОСБОРКА НЕ ОЗНАЧАЕТ АВТОЗАПУСК. Сочинённая спека проходит те же ворота стоимости,
что объявленная: класс цены выводится из САМОГО ДОРОГОГО шага, и дорогая цепочка так же
предлагается кнопкой, а не запускается сама.

⚠️ ИМЯ И ЯРЛЫК — ДЕТЕРМИНИРОВАННЫЕ, без вызова модели. Просить у неё название значило бы
платить за каждое предложение и получать разные имена на одну и ту же цепочку.
"""

from __future__ import annotations

from service.domain.capabilities.agent_spec import COST_CHEAP, COST_CLASSES

from .observation import Chain

# Сколько предложений на тред. ⚠️ Потолок нужен: без него каждое сообщение после третьего
# повтора приносило бы карточку — и предложение из полезного превратилось бы в помеху.
MAX_OFFERS_PER_THREAD = 1


# Сколько символов запроса человека берём в подсказку маршрута. Длинная подсказка
# вытесняет остальные маршруты из промпта, короткая ничего не говорит.
MAX_HINT_CHARS = 120


def hint(chain: Chain, user_prompt: str, labels: dict[str, str]) -> str:
    """Подсказка оркестратору: КОГДА выбирать этот сценарий.

    🔴 БЕЗ НЕЁ ЗАКРЕПЛЕНИЕ БЕССМЫСЛЕННО. Блок маршрутов промпта собирается ТОЛЬКО из спек
    с непустым `prompt_hint` (`derived._prompt_routes`): сценарий без подсказки хранится,
    но выбрать его модель не может никогда — кнопка нажата, а поведение прежнее.

    ⚠️ Берём НАСТОЯЩИЙ запрос человека, а не сочиняем описание. Выдуманная формулировка
    сместила бы маршрутизацию туда, где сценарий не нужен, — а этот текст и есть тот
    случай, ради которого его закрепляют. Если запроса нет, описываем состав шагов: хуже,
    чем по живому примеру, но лучше, чем ничего — иначе спека снова станет невыбираемой.
    """
    example = " ".join(str(user_prompt or "").split())[:MAX_HINT_CHARS].strip()
    if example:
        return f"повторяющийся сценарий пользователя, например: «{example}»"
    steps = " → ".join(labels.get(step, step) for step in chain.steps)
    return f"повторяющийся сценарий: {steps}"


def proposal(
    chain: Chain, *, labels: dict[str, str], costs: dict[str, str], user_prompt: str = ""
) -> dict:
    """Спека-кандидат: как её показать человеку и чем она станет, если он согласится.

    Отдаём СЛОВАРЬ, а не `WorkflowSpec`: спека будет собрана на той стороне, где её
    сохранят, и собирать её здесь — значит завести второе место, где она рождается.
    Форма при этом ровно та, что принимает `WorkflowSpec`.
    """
    steps = list(chain.steps)
    return {
        # Имя не показывается человеку и обязано быть устойчивым: одна и та же цепочка
        # должна давать одно и то же имя, иначе повторное согласие заведёт вторую копию.
        "name": "saved_" + "_".join(steps),
        "label_ru": " → ".join(labels.get(step, step) for step in steps),
        "steps": steps,
        # Без подсказки спека невыбираема: блок маршрутов промпта берёт только те, у кого
        # она есть. Закрепление без неё меняло бы содержимое БД и ничего больше.
        "prompt_hint": hint(chain, user_prompt, labels),
        # 🔴 КЛАСС ЦЕНЫ — ПО САМОМУ ДОРОГОМУ ШАГУ. Цепочка не может быть дешевле своего
        # дорогого звена: посчитав её дешёвой, платформа запускала бы ресёрч внутри
        # «обычного» сценария без единого вопроса.
        "cost_class": _worst_cost(steps, costs),
        "confirm_by_default": _worst_cost(steps, costs) != COST_CHEAP,
    }


def _worst_cost(steps: list[str], costs: dict[str, str]) -> str:
    """Самый дорогой класс среди шагов. Незнакомый шаг считаем дешёвым — он и не запустится."""
    worst = 0
    for step in steps:
        rank = (
            COST_CLASSES.index(costs.get(step, COST_CHEAP))
            if costs.get(step) in COST_CLASSES
            else 0
        )
        worst = max(worst, rank)
    return COST_CLASSES[worst]
