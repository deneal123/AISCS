"""Схема личности и правила композиции микса.

Личность — набор текстовых фрагментов по слотам плюс метаданные. Обязательны только
`id`, `label` и `core.identity`: личность должна прототипироваться за минуту и
дополняться по мере надобности, а не требовать заполнения пятнадцати полей сразу.

Отсутствие слота — не пустая строка, а «в этой точке личность молчит»: там работает
штатный универсальный промпт субагента. Субагенты обязаны оставаться самостоятельными
и без личности.
"""

from __future__ import annotations

import logging

from pydantic import BaseModel, ConfigDict, Field, field_validator

from service.domain.persona import slots as slot_names

logger = logging.getLogger(__name__)

# Потолок числа одновременно активных личностей. Больше — каша: каждая добавляет свой
# текст в общий бюджет, а различимость специализаций падает быстрее, чем растёт польза.
# ДВЕ — это и есть «связка»: пара даёт новый угол (психолог+таролог), а тройка уже
# размывает каждую до неразличимости.
MAX_ACTIVE: int = 2


class PersonaCore(BaseModel):
    """Ядро личности: кто ты, как думаешь, как говоришь, как оформляешь ответ."""

    model_config = ConfigDict(extra="forbid")

    identity: str
    method: str = ""
    # Что делать, когда материала для метода НЕТ. Без этого поля личность растворяется
    # в теме вопроса: живой прогон показал таролога, который на вопрос без единого
    # символа выдал астрологию и китайский календарь — формально не нарушив `identity`
    # («читаешь материал как знаковую систему»), потому что материала ему не дали, а
    # предложить свой инструмент никто не велел.
    initiative: str = ""
    tone: str = ""
    output: str = ""


class PersonaSpec(BaseModel):
    """Одна личность из реестра."""

    model_config = ConfigDict(extra="forbid")

    id: str
    label: str
    enabled: bool = True
    # Порядок в КАТАЛОГЕ (что показать первым в селекторе). Меньше — выше.
    # ⚠️ НА КОМПОЗИЦИЮ НЕ ВЛИЯЕТ, и это изменение по результатам живого прогона. Раньше
    # ведущую в миксе выбирал именно `priority` — и «таролог» (70) не мог возглавить ни
    # одну пару, потому что был последним числом во всей поставке. Пользователь выбирал
    # «психолог+таролог», а получал голос психолога, и объяснения этому в интерфейсе не
    # было никакого: число живёт в JSON админки. Ведущая теперь — ПЕРВАЯ ВЫБРАННАЯ.
    priority: int = 100
    # Личности, с которыми эта заведомо несовместима по смыслу.
    blend_deny: list[str] = Field(default_factory=list)
    # Пояснение ДЛЯ ЧЕЛОВЕКА в интерфейсе. В промпт НЕ идёт: реестр хранит инструкции
    # для модели, а пользователю нужен другой жанр — показывать ему системный промпт
    # незачем. Живёт здесь, а не во фронте: новая личность из админского JSON обязана
    # получать подсказку без выката фронта, как и иконку по умолчанию.
    hint: str = ""
    core: PersonaCore
    slots: dict[str, str] = Field(default_factory=dict)
    disclaimers: list[str] = Field(default_factory=list)

    @field_validator("slots")
    @classmethod
    def _known_slots_only(cls, value: dict[str, str]) -> dict[str, str]:
        """Неизвестный слот — ОШИБКА, а не молчаливый пропуск.

        Опечатка в имени слота иначе означала бы личность, которая настроена и не
        действует: в промпт не уходит ничего, а видно это только по качеству ответов.
        """
        unknown = slot_names.unknown_slots(value)
        if unknown:
            raise ValueError(
                f"неизвестные слоты: {unknown}. Допустимые: {sorted(slot_names.SLOTS)}"
            )
        return value


def resolve_bundle(specs: list[PersonaSpec]) -> list[PersonaSpec]:
    """Отобрать личности к применению: выключенные прочь, конфликты и потолок разрешены.

    ⚠️ ПОРЯДОК СОХРАНЯЕТСЯ ВХОДНОЙ — то есть порядок выбора пользователем, и первая
    выбранная становится ведущей (её тон, формат ответа и исключающие слоты). Раньше
    здесь стояла сортировка по `priority` с обоснованием «одинаковый НАБОР обязан давать
    байт-идентичный промпт». Обоснование не выдержало живого прогона: воспроизводимость
    оно давало, а управляемость отнимало — выбрать ведущую было нельзя вообще, и
    «таролог» с его 70 не возглавлял ни одну пару в поставке.

    Детерминизм при этом НЕ ТЕРЯЕТСЯ, меняется только его формулировка: одинаковый
    СПИСОК даёт байт-идентичный промпт. Порядок — часть входа, а не случайность; он
    приезжает в `persona_ids` и виден пользователю в селекторе.

    Деградация здесь ВИДИМАЯ: всё отброшенное логируется с причиной. Молча уронить
    выбор пользователя — значит оставить его гадать, почему личность «не работает».
    """
    live = [s for s in specs if s.enabled]

    kept: list[PersonaSpec] = []
    for spec in live:
        denied_by = next(
            (k.id for k in kept if spec.id in k.blend_deny or k.id in spec.blend_deny), None
        )
        if denied_by:
            logger.info("персона '%s' отброшена: несовместима с '%s'", spec.id, denied_by)
            continue
        if len(kept) >= MAX_ACTIVE:
            logger.info("персона '%s' отброшена: превышен потолок %s", spec.id, MAX_ACTIVE)
            continue
        kept.append(spec)
    return kept
