"""Снятие markdown-ограждения с JSON-ответа модели.

⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Модели регулярно оборачивают JSON в ```` ```json … ``` ````,
хотя их об этом не просили, и разбор без снятия ограждения падает. Обходили это ЧЕТЫРЬМЯ
разными способами — в декомпозиции, роутере, генерации презентаций и нативном ресёрче, —
и все четыре ведут себя по-разному на неровном ответе:

* `raw.strip("`")` + срез `"json"` — снимает ЛЮБОЕ число обратных кавычек с обоих концов,
  включая те, что часть содержимого;
* регулярка с `MULTILINE` — трогает ограждение в СЕРЕДИНЕ текста, а не только по краям;
* `split("\n", 1)[-1]` — теряет первую строку, если ограждения нет вовсе, но текст
  начинается с чего-то похожего.

Разница проявляется не всегда, а на первом же нестандартном ответе — и в каждом месте
по-своему. Здесь один разбор, консервативный: снимаем ограждение, только если оно
действительно обрамляет весь текст.
"""

from __future__ import annotations

import re

# Открывающее ограждение: ``` или ~~~, необязательный ярлык языка, до конца строки.
_OPEN_RE = re.compile(r"^(```|~~~)[^\n]*\n")
_CLOSE_RE = re.compile(r"\n(```|~~~)\s*$")


def strip_json_fence(text: str) -> str:
    """Вернуть содержимое ```` ```json … ``` ````; текст без ограждения — как есть.

    Консервативно по устройству: снимаем ТОЛЬКО парное ограждение, обрамляющее весь
    ответ. Одинокая открывающая или закрывающая тройка — скорее часть содержимого
    (модель показывает пример кода), и трогать её нельзя.
    """
    raw = str(text or "").strip()
    open_match = _OPEN_RE.match(raw)
    if not open_match:
        return raw
    close_match = _CLOSE_RE.search(raw)
    if not close_match:
        return raw
    return raw[open_match.end() : close_match.start()].strip()
