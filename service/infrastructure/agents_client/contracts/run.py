"""DTO входного запроса ``/run`` сайдкара agents — КОПИЯ ПОТРЕБИТЕЛЯ.

Сериализуемое тело, которое backend (``HttpAgentEngine``, Фаза 4) кладёт в ``POST /run``,
а сайдкар разворачивает в вызов движка. Отражает вход ``AgentExecutionPort.execute``, но
БЕЗ несериализуемого:

* ``pseudo_session`` — не входит: историю треда несёт ``history_messages`` (Фаза 0b,
  stateless), а локальную сессию сайдкар при желании строит из неё сам;
* ``on_event`` — не входит: стриминг событий обратно это забота ТРАНСПОРТА (SSE/NDJSON
  ответа ``/run``), а не тела запроса.

Поля памяти/истории/резюме (``memory_parts``/``history_messages``/``compact_summary``) —
ровно те, что backend теперь собирает САМ и передаёт данными (Фаза 0b). Контракт-инвариант
проверяется тестом против реальной сигнатуры ``execute`` — DTO не должен «уплыть» от порта.
"""

from typing import Any

from pydantic import BaseModel, ConfigDict

# Поля тела, которые НЕ являются аргументами ``execute``: они описывают окружение
# прогона, и сторона исполнения разворачивает их сама (сейчас — снимок провайдерной
# политики в ContextVar). Держим списком, чтобы страж-тест «поля DTO ⊆ сигнатура
# execute» продолжал ловить настоящий дрейф контракта, а не спотыкался об окружение.
AMBIENT_FIELDS = frozenset({"provider_policy", "agent_settings", "mcp_server_ids"})


class AgentRunInput(BaseModel):
    """Тело ``POST /run`` — полный сериализуемый вход прогона движка агента."""

    text: str
    thread_id: str
    user_id: str | None = None
    session_data: dict | None = None
    selected_model: str | None = None
    route_override: str | None = None
    # Категория, уже выбранная авто-роутером сайдкара в `/route`. Пусто → сайдкар
    # определит сам (ручной выбор модели: авто-роутер там не звался).
    #
    # ⚠️ СЕГОДНЯ BACKEND НЕ ЗАПОЛНЯЕТ ЭТО ПОЛЕ НАПРЯМУЮ. Значение едет в воркер внутри
    # `session_data['_resolved_category']` (`chat_job_orchestrator`) — тем же каналом и
    # по той же причине, что и `routing_usage`: между `/route` и `/run` десяток слоёв, и
    # протягивать через каждый ещё один аргумент значит завести десяток мест, где можно
    # тихо не дотянуть. Сайдкар разбирает канал в одном месте (`schemas/run.py`).
    # Поле объявлено, чтобы контракт был виден целиком и его держал парити-гейт.
    resolved_category: str | None = None
    input_type: str | None = None
    web_search: bool = False
    deep_research: bool = False
    file_context: str = ""
    attachments: list | None = None
    memory_enabled: bool = True
    ldr_model: str | None = None
    ldr_strategy: str | None = None
    multi_intent: bool | None = None
    # Собрано backend'ом (stateless, Фаза 0b): сайдкар НЕ ходит в MemOS/PG/Redis backend'а.
    memory_parts: tuple[str, str] | None = None
    history_messages: list[dict] | None = None
    compact_summary: str | None = None
    # Табличные файлы пользователя для инструмента ``analyze_data``. Кладём НЕ байты, а
    # ПРЕЗАЙНЕД-ССЫЛКИ: файл может весить десятки мегабайт, а инструмент вызывается
    # редко — тело /run не раздуваем, сайдкар скачает ЛЕНИВО и только если инструмент
    # реально сработал. Формат: ``[{"name": "t1.csv", "url": "https://…"}]``.
    tabular_files: list[dict] | None = None
    # Презайнед-ссылка на ПОСЛЕДНЮЮ картинку треда — для image-to-image («перегенерируй с
    # другим цветом волос»). Собирает backend из истории треда; субагент применяет только
    # когда текст просит правку. Ссылкой, не байтами: картинка тяжёлая.
    reference_image_url: str | None = None
    # graph_id репозиториев треда для search_knowledge_graph (код репо, не только
    # личные документы). Привязаны на аплоаде, собраны воркером из Redis треда.
    repo_graph_ids: list[str] | None = None
    # Приложен ли в этом сообщении нетабличный файл (документ/репозиторий/код) рядом с
    # табличным → сайдкар не выбрасывает file_context при наличии таблиц (иначе карта
    # репо/документ пропадёт из промпта). Живой инцидент: .json-датасет + .zip-репо.
    has_non_tabular_attachment: bool = False
    # Выбранные пользователем личности (специализации агента). Едет ВЫБОР; сами
    # определения приезжают админ-снимком в `agent_settings` — выбор персональный и
    # меняется каждым сообщением, а реестр общий.
    persona_ids: list[str] | None = None
    # Роль сменилась по сравнению с прошлым ответом в треде — считает backend, у него
    # есть история с метаданными. Без явного разрыва смена личности посреди диалога
    # почти не действует: инструкция не спорит с демонстрацией из предыдущих ходов.
    persona_switched: bool = False
    # Планирование сложных задач: `None` — авто (по оценке сложности), `True` — всегда,
    # `False` — никогда. Стратегия поверх «Авто», как мульти-интент, а не маршрут.
    planning: bool | None = None
    # Ссылка на файловую песочницу прогона: {workspace_id, token, user_id, root}.
    # 🔴 С ТОКЕНОМ ВЛАДЕНИЯ: без подписи угаданный `workspace_id` был бы доступом к чужой
    # файловой системе. Выдаёт сайдкар песочниц при создании, backend лишь несёт дальше.
    # Пусто — инструменты `ws_*` не выдаются модели вовсе (умолчание на стороне отказа).
    workspace_ref: dict | None = None
    # 🔴 СОГЛАСИЕ ЧЕЛОВЕКА НА ПРОСМОТР РОЛИКА. Поле обязано быть ЗДЕСЬ: тело `/run`
    # собирается фильтром «только поля контракта», и всё остальное молча выбрасывается.
    # Признак ставился нажатием кнопки, доезжал до `engine_env` — и терялся ровно на
    # этой границе. Замер: сайдкар video получал только health-пробы, а человек читал
    # «Режим „просмотр видео“ не запускался».
    video_tool_enabled: bool = False
    # Снимок провайдерной политики (кто выключен админом / заблокирован health-проверкой).
    # Это ОКРУЖЕНИЕ прогона, а не вход пайплайна: читают его модульные функции глубоко в
    # мультипровайдерном слое, поэтому сторона исполнения кладёт снимок в ContextVar
    # (``service.shared.provider_policy_context`` на стороне сайдкара), а не
    # аргументом. Отсюда и
    # исключение из ``to_execute_kwargs``. Формат: ``{"disabled": [...], "blocked": [...]}``.
    provider_policy: dict | None = None
    # Слепок ПЕРЕОПРЕДЕЛЁННЫХ админом runtime-настроек агентов (admin-overlay живёт в БД
    # backend'а). Тоже окружение прогона: домен читает их через
    # ``service.shared.agent_settings`` на стороне сайдкара, а не аргументом.
    # Чего нет в слепке — берётся из
    # конфига стороны исполнения. Формат: ``{"duckdb_enabled": false, ...}``.
    agent_settings: dict | None = None
    # 🔴 ИДЕНТИФИКАТОРЫ разрешённых MCP-серверов, а НЕ адреса. Адрес в теле запроса —
    # прямой SSRF во внутреннюю сеть: там Postgres, Redis, MinIO, Qdrant и все сайдкары
    # отвечают без аутентификации, по одной топологии. Сопоставление
    # «идентификатор → адрес и секрет» живёт в админ-настройках и на провод не выходит.
    # Тоже окружение прогона: набор читает подключение MCP на входе, а не пайплайн.
    # Пусто — MCP не задействован (умолчание на стороне безопасности).
    mcp_server_ids: list[str] | None = None

    # Прощаем незнакомые поля (forward-compat: backend новее сайдкара — лишние поля
    # игнорируем, а не роняем весь прогон на ValidationError).
    model_config = ConfigDict(extra="ignore")

    def to_execute_kwargs(self) -> dict[str, Any]:
        """Развернуть в kwargs ``AgentExecutionPort.execute``.

        ``pseudo_session``/``on_event`` сюда НЕ входят — их подставляет сторона
        исполнения: сессия строится из ``history_messages``, ``on_event`` — колбэк
        транспорта стрима. Поля из ``AMBIENT_FIELDS`` тоже не входят: они едут в теле,
        но разворачиваются в окружение прогона, а не в аргументы движка.
        """
        return {k: v for k, v in self.model_dump().items() if k not in AMBIENT_FIELDS}
