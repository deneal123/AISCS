"""Оценка числа токенов без токенизатора.

Копия есть у обеих сторон — и это НЕ безобидно: у backend есть путь, где оценка
становится фактическим списанием (провайдер не вернул usage → списываем по
резерву). У сайдкара она режет контекст под окно модели.

Расхождение ловится общими векторами (`tests/vectors/token_estimate_vectors.json`,
сверяются побайтово в CI суперпроекта), а не общим пакетом.
"""

from __future__ import annotations

import math

# 🔴 КОЭФФИЦИЕНТЫ ОТКАЛИБРОВАНЫ ЗАМЕРОМ, а не подобраны на глаз. Прежняя модель
# «латиница 4.0 / кириллица 2.5» ошибалась в ОБЕ стороны, и сильно: сверка с настоящими
# токенизаторами (RouterAI/gpt-4o-mini и GigaChat-2-Max) на корпусе из шести образцов
# дала +51% на русской прозе и −9% на markdown. Первое жжёт деньги (сжатие включается
# там, где текст и так влезал, а одно сжатие — до 13 вызовов модели), второе опаснее:
# ЗАНИЖЕНИЕ переполняет окно, и ответ обрывается.
#
# Настоящий предсказатель — не алфавит, а ПЛОТНОСТЬ РАЗМЕТКИ. Замер (симв/токен):
#   проза русская 4.15 · проза английская 5.53 · смешанный текст 3.75
#   код 3.84 · markdown с таблицами 3.00
# Кириллица у нынешних токенизаторов кодируется вдвое лучше, чем предполагала старая
# формула; а вот пунктуация, разметка и идентификаторы дробят текст сильно.
#
# Коэффициенты взяты по ХУДШЕМУ (плотнейшему) из двух провайдеров, чтобы оценка всегда
# ЗАВЫШАЛА: запас по корпусу +4…+39%, минимум +4% на смешанном тексте. Направление
# ошибки — решение, а не случайность.
_CPT_DENSE = 3.0  # плотный текст: разметка, таблицы, код
_CPT_PROSE = 4.0  # сплошная проза
_ALNUM_DENSE = 0.65  # доля букв/цифр, ниже которой текст считаем плотным
_ALNUM_PROSE = 0.85  # и выше которой — сплошной прозой
_CYRILLIC_PENALTY = 0.6  # кириллица всё ещё чуть дороже латиницы, но не вдвое


def estimate_tokens(text: str) -> int:
    """Грубая оценка числа токенов в строке (без токенизатора).

    Два сигнала: доля букв и цифр (сплошная проза кодируется вдвое эффективнее разметки)
    и доля кириллицы (она чуть дороже латиницы). Коэффициенты — из замера против
    настоящих токенизаторов, см. комментарий выше.

    ⚠️ Оценка ОБЯЗАНА завышать. Занижение переполняет окно модели и обрывает ответ;
    завышение стоит лишних сжатий. Обе ошибки денежные, но первая ещё и видна юзеру.
    """
    s = str(text or "")
    if not s:
        return 0
    total = len(s)
    cyr_ratio = sum(1 for ch in s if "Ѐ" <= ch <= "ӿ") / total
    alnum_ratio = sum(1 for ch in s if ch.isalnum()) / total
    prose = min(1.0, max(0.0, (alnum_ratio - _ALNUM_DENSE) / (_ALNUM_PROSE - _ALNUM_DENSE)))
    chars_per_token = _CPT_DENSE + (_CPT_PROSE - _CPT_DENSE) * prose - _CYRILLIC_PENALTY * cyr_ratio
    return max(1, math.ceil(total / max(0.5, chars_per_token)))
