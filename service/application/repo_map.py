"""Карта репозитория в контексте: как её распознать и что о ней сказать.

Отдельный модуль, а не пара функций в подготовке конвейера: у карты своя причина меняться
(формат отчёта graphify), и знают о ней ровно два потребителя — текст промпта и признак для
решателя. Пока они лежали вперемешку с шагами конвейера, второго не было вовсе.

🔴 КАРТА — НЕ СОДЕРЖИМОЕ. Это узлы и связи БЕЗ тел функций. Различие не косметическое: по
нему решается, выдадут ли агенту файловые инструменты, и пока карту считали «текстом
вложения», человек с архивом кода получал рассуждения об архитектуре вместо разбора.
"""

from __future__ import annotations

# Маркеры отчёта graphify: заголовок + характерная секция. Совпасть случайно в обычном
# markdown практически невозможно — требуем И заголовок, И секцию.
_REPO_MAP_MARKERS = ("# Graph Report", "God Nodes")

# 🔴 ВТОРАЯ ФОРМА ТОГО ЖЕ: ПЕРЕЧЕНЬ ФАЙЛОВ БЕЗ ГРАФА. На не-кодовом архиве (замерено на
# стилях TMLR — LaTeX) graphify отвечает «graph is empty», и вложение приезжает одним
# перечнем файлов. Для решателя это тот же случай: содержимое лежит в песочнице, а не в
# контексте. Без этого маркера инструменты снова снимались бы, и агент отвечал бы по
# списку имён — ровно та жалоба, с которой всё началось.
_ARCHIVE_LISTING_MARKER = "# Файлы архива ("

_REPO_MAP_INSTRUCTION = (
    "🔴 ПОРЯДОК ДЕЙСТВИЙ НА ЭТОТ ХОД, ОБЯЗАТЕЛЬНЫЙ.\n"
    "1. ПЕРВЫМ шагом выбери инструмент ПО ВОПРОСУ, а не наугад:\n"
    "   • вопрос ОБЗОРНЫЙ («что в проекте», «изучи», «расскажи, что это») — начни с "
    "`ws_list`, затем `ws_read` по README и главным файлам. Шаблон для поиска тут НЕ НУЖЕН, "
    "и спрашивать его не у кого;\n"
    "   • вопрос ТОЧЕЧНЫЙ (найти функцию, ошибку, упоминание) — `ws_grep` по этому слову.\n"
    "   Исходники архива уже развёрнуты в твоём рабочем каталоге.\n"
    "2. Открой найденное через `ws_read`. СПИСОК ФАЙЛОВ — НЕ ОТВЕТ: если вопрос широкий "
    "(«отревьюй», «что тут за проект»), выбери 2–4 главных файла САМ — README и манифест "
    "проекта, дальше по весам узлов в карте, — и прочитай их. Не спрашивай, с чего начать и "
    "что искать: это решаешь ты.\n"
    "3. Только теперь отвечай — и отвечай ПО ПРОЧИТАННОМУ, цитируя код.\n"
    "\n"
    "🔴 НИЖЕ НЕ КОД, А КАРТА: имена файлов, связи и их веса. Ни одной строки кода в ней нет, "
    "поэтому ответ по одной карте — это пересказ имён и чисел, то есть выдумка. «41 связь» "
    "не говорит, что делает функция. Карта годится ТОЛЬКО чтобы выбрать, какой файл открыть.\n"
    "\n"
    "Запрещено, потому что уже случалось:\n"
    "— отвечать «судя по карте / вероятно / похоже, это библиотека…» вместо чтения файла;\n"
    "— искать этот код в интернете (`fetch_url`, веб-поиск): он лежит РЯДОМ, а из сети "
    "приедет чужая версия или 404 — так и вышло, восемь вызовов подряд впустую;\n"
    "— заканчивать ход вопросом вместо работы: «могу открыть файл, продолжать?», «с чего "
    "начнём?», «какие файлы смотреть?», «уточните, что именно искать». Человек уже "
    "попросил: выбирай файлы и читай;\n"
    "— просить «приложить код»: он загружен.\n"
    "\n"
    "⚠️ Если рабочий каталог окажется ПУСТ (файлы до него не доехали) — тот же код доступен "
    "через `search_knowledge_graph`. Это единственная замена чтению; выдумывать вместо неё "
    "нельзя, а честное «файлов не вижу» лучше пересказа карты.\n"
    "⚠️ Карту используй как НАВИГАЦИЮ: по весам узлов видно, какие файлы открывать первыми.\n"
    "⚠️ Карта снята НА МОМЕНТ ЗАГРУЗКИ и о твоих правках не знает: сверяйся с "
    "`ws_read`/`ws_diff`, а не с ней.\n\n"
)


def is_repo_map(file_context: str | None) -> bool:
    """В контексте КАРТА репозитория, а не содержимое файла.

    🔴 РАЗЛИЧИЕ РЕШАЕТ, ВЫДАДУТ ЛИ ИНСТРУМЕНТЫ ВООБЩЕ. Решателю сообщали булево «текст
    вложения в контексте есть», и для архива оно было ИСТИНОЙ: карта непуста. По правилу
    «приложенный документ сам по себе ничего не значит, читать его инструментами не нужно»
    он ставил `needs_files: false`, и девять инструментов `ws_*` не выдавались. Человек
    загружал архив с кодом и получал общие рассуждения об архитектуре: посмотреть код
    агенту было нечем, а сказать об этом — тоже нечем.

    Два блока промпта при этом противоречили друг другу: приписка ниже говорила модели
    «полный код доступен инструментом», а признак говорил решателю «инструменты не нужны».
    Выигрывал признак — он снимает инструменты ДО прогона, когда спорить уже некому.

    ⚠️ Замер поправил гипотезу: на «отревьюй код» решатель отвечал `true` и раньше,
    переключилось «объясни, что тут происходит». Дыра настоящая, но уже, чем казалась.
    """
    text = str(file_context or "")
    return all(m in text for m in _REPO_MAP_MARKERS) or _ARCHIVE_LISTING_MARKER in text


def annotate_repo_map(file_context: str) -> str:
    """Приписать инструкцию, если в контексте карта репозитория.

    🔴 Карта — это узлы и связи без тел функций, и агент, видя структуру, просил
    «приложить код». Инструкция закрывает разрыв: карта = навигация, код = инструмент.

    🔴 ЗАМЕР ПОКАЗАЛ, ЧТО ПРЕЖНЕЙ РЕДАКЦИИ БЫЛО НЕ ДОСТАТОЧНО. Сквозной прогон на живом
    стенде: песочница выдана, исходники `requests` развёрнуты в ней деревом, решатель
    поставил `files_tool: true`, инструменты `ws_*` выданы — и модель НЕ ПОЗВАЛА НИ ОДНОГО,
    ответив «объясню проект по этой карте» с рассуждением про «41 связь». Ровно то, на что
    пожаловался человек.

    ⚠️ ЧЕСТНО О ГРАНИЦАХ ЭТОГО ТЕКСТА. Следующие два замера (вопрос «покажи код функции»)
    я сперва счёл его провалом: модель упорно шла в `fetch_url`. На деле в тех прогонах
    решатель отвечал `files_tool: false`, инструментов `ws_*` у модели НЕ БЫЛО, и поиск кода
    в сети был её единственным разумным ходом. То есть текст правился трижды там, где
    ломалось ПРАВИЛО РЕШАТЕЛЯ. Урок: прежде чем править промпт, убедись, что инструмент
    вообще выдан — omissions прогона говорят это прямо.

    Две причины, по которым прежняя редакция всё же была слабой:

    * инструкция называла ОДИН инструмент, `search_knowledge_graph`, а он выдаётся по
      своему гейту (`repo_graph_ids`) и в том прогоне был ОТКАЗАН. Модель не нашла
      названного средства и ответила тем, что было под рукой;
    * про рабочий каталог говорилось «сверяйся» — это про правки, а не про чтение, и как
      указание прочитать код перед ответом оно не читается вовсе.

    🔴 ЧТО РЕШИЛО ДЕЛО: ПРОНУМЕРОВАННЫЙ ПОРЯДОК ДЕЙСТВИЙ вместо пожелания в прозе. Замер на
    пяти вопросах про код (архив `requests` в песочнице), до и после:

        вопрос                        ws-вызовы   веб-поиск   код в ответе
        покажи код функции            0 → 2       1 → 0       нет → ДА
        объясни, что тут происходит   2 → 7       0 → 0       нет → ДА
        найди обработку таймаутов     1 → 1       0 → 0       да → да
        отревьюй качество кода        0 → 5       0 → 0       см. ниже
        какие зависимости             3 → 2       0 → 0       список, кода и не нужно

    Просьба «сначала прочитай файлы, потом отвечай» давала чтение в 1 случае из 5; «1. ПЕРВЫМ
    вызови… 2. Открой… 3. Только теперь отвечай» — во всех пяти, и веб-поиск исчез совсем.

    ⚠️ ВТОРАЯ НАХОДКА ТОГО ЖЕ ЗАМЕРА: на «отревьюй качество» модель дважды звала `ws_list`,
    получала 8 КБ дерева и заканчивала ход словами «С чего начнем?». Прежний запрет касался
    ФОРМУЛИРОВКИ «могу открыть файл, продолжать?» — а запрет формулировки всегда обходится
    другой. Правило переписано про ДЕЙСТВИЕ: список файлов не ответ, выбор делает агент.
    После правки — 5 чтений и ревью, ссылающееся на `resolve_redirects`, `merge_setting`,
    `merge_hooks`: этих имён в карте нет, значит код действительно прочитан.

    ⚠️ ЦЕНА НАЗВАНА ПРЯМО: до 7 раундов инструментов на вопрос, а каждый переотправляет весь
    растущий диалог. Это осознанный обмен — прежде та же цена платилась за ответ «объясню по
    карте», то есть ни за что.
    """
    text = str(file_context or "")
    return _REPO_MAP_INSTRUCTION + text if is_repo_map(text) else text
