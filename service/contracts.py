"""Контракт сайдкара duckdb: то, на что опирается вызывающий.

Модуль намеренно ЛЁГКИЙ — только stdlib, без `duckdb` и `openpyxl`. Причина та же, что у
`agents/service/contracts.py`: сверку контракта гоняет CI суперпроекта, и она не должна
тянуть за собой движок ради нескольких множеств строк. Тяжёлый импорт превратил бы дешёвую
проверку в установку зависимостей — и её бы просто не поставили гейтом.

Константы объявлены ЗДЕСЬ, а `core.py`/`app.py` их импортируют: источник правды один. Тесты
сверяют, что реально отдаваемые словари совпадают с этими множествами — список, живущий
отдельно от кода, разъехался бы с ним и перестал что-либо гарантировать.
"""

from __future__ import annotations

import os

# Версия КОНТРАКТА, не образа. Поднимать при несовместимом изменении формы запроса или
# ответа; публикуется в `/health`, чтобы вызывающий видел, с кем говорит.
SERVICE_VERSION = "1.0.0"
SERVICE_NAME = "duckdb"

# Потолок тела запроса: файлы приходят base64 (≈+33%), поэтому лимит выше «сырого».
#
# ⚠️ ЭТО ЖЕ ЧИСЛО ОБЯЗАН ЗНАТЬ КЛИЕНТ. Сейчас у него свой потолок (`duckdb_max_bytes`,
# 48 МБ) против серверных 64 МБ: запрос между этими границами клиент пропускает, а сервер
# отвергает — отказ выглядит как сбой сайдкара, хотя это расхождение настроек. Числа
# сверяет офлайн-гейт `scripts/check_contract_parity.py`.
MAX_BODY_BYTES = int(os.environ.get("DUCKDB_MAX_BODY_BYTES", str(64 * 1024 * 1024)))

# ⚠️ СЕРВЕРНЫЙ ДЕДЛАЙН ОБЯЗАН БЫТЬ МЕНЬШЕ КЛИЕНТСКОГО. До его появления таймаута на
# выполнение SQL не было ВООБЩЕ: клиент отваливался по своим 60 с, а сервер продолжал
# считать запрос, написанный моделью, — процессорное время горело без потребителя, и
# заметить это было нечем. Разрыв в 15 с оставлен на сериализацию и сеть.
QUERY_TIMEOUT_SEC = float(os.environ.get("DUCKDB_QUERY_TIMEOUT_SEC", "45"))

# Ключи успешного ответа `POST /query`. Вызывающий читает их через `.get(...)`, поэтому
# переименование здесь не падает, а тихо отдаёт пустоту.
RESPONSE_FIELDS = frozenset(
    {
        "sql",
        "columns",
        "rows",
        "row_count",
        "truncated",
        "tables",
        "duration_sec",
    }
)

# Машинные коды ошибок. Текст в `detail` меняется свободно, код — часть контракта: по нему
# вызывающий отличает «поправь запрос» от «сервис недоступен».
#
# ⚠️ `sql_error` отдаётся с HTTP 200 ОСОЗНАННО, и это единственное отступление от общего
# правила «ошибка = не-2xx». Неверный SQL здесь не сбой транспорта, а нормальный ход
# диалога: текст ошибки возвращается модели, чтобы она исправила запрос. Отступление
# названо явно, чтобы отличаться от недосмотра.
ERROR_CODES = frozenset(
    {
        "invalid_request",  # 422 — тело не прошло схему
        "no_files",  # 400
        "request_too_large",  # 413
        "unsupported_format",  # 415
        "not_found",  # 404
        "query_timeout",  # 504
        "query_failed",  # 500
        "sql_error",  # 200 — см. выше
    }
)
