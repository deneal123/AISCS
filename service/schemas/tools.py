"""Схемы тела `/tools/*`.

⚠️ ЗАЧЕМ ОНИ ПОЯВИЛИСЬ. Эти три ручки принимали `payload: dict` и разбирали его вручную
через `.get()`. Следствия, каждое молчаливое:

* забытое поле превращалось в `""` — запрос без `query` возвращал пустой список
  результатов, и вызывающий не мог отличить «ничего не нашли» от «я забыл передать
  запрос». Поэтому здесь у полей ОБЯЗАТЕЛЬНОСТЬ, а не дефолт: все вызывающие их и так
  всегда шлют (`backend/.../sidecar_tools.py`), так что строгость никого не ломает, а
  ошибку вызывающего называет по имени поля;
* `{"num_results": "много"}` доезжал до `int()` и падал 500 — ошибка ВЫЗЫВАЮЩЕГО
  выглядела поломкой сервиса;
* границы (`num_results ≤ 10`) жили в теле обработчика как `min(...)`, поэтому снаружи
  их было не видно, а превышение молча урезалось.

Это же требование регламента: один способ описания запроса — pydantic-схема.
"""

from __future__ import annotations

from pydantic import BaseModel, Field


class WebSearchRequest(BaseModel):
    query: str
    # Потолок был зашит в обработчике как `min(..., 10)`. В схеме он ЧАСТЬ КОНТРАКТА:
    # виден снаружи, и превышение даёт 422 с именем поля, а не тихое урезание.
    #
    # ⚠️ Нижняя граница не для симметрии: `num_results` приезжает из query-параметра
    # пользовательской ручки backend'а, где верх обрезан, а низ — нет. Ноль и минус
    # доезжали сюда и давали пустой список (`len(results) >= -5` истинно сразу) —
    # то есть «поиск ничего не нашёл» вместо «параметр бессмысленный».
    num_results: int = Field(default=5, ge=1, le=10)


class ParseUrlRequest(BaseModel):
    url: str


class PptxRequest(BaseModel):
    topic: str
    # Пустая строка = «выбери сам»: выбор модели — забота владельца провайдеров,
    # backend не знает, кто из них жив. Поэтому у `model` дефолт есть, а у `topic` нет.
    model: str = ""
