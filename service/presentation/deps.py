"""Общие зависимости HTTP-слоя: авторизация внутренних ручек.

Открытой остаётся ровно одна ручка — `/health`: её дёргает compose, и требовать там ключ
значило бы отдать здоровье контейнера на откуп конфигурации секретов. Всё остальное —
`/run`, `/route`, `/catalog*`, `/providers/*`, `/tools/*`, `/vector/*`, `/media/*` —
несёт пользовательские данные, деньги или секреты и закрыто.

⚠️ Отдельного секрета для внутренних ручек НЕТ намеренно: вызывающий у них один и тот
же (backend), и второй ключ лишь удвоил бы место, где он протухнет. Ключ тот же, что у
`/v1`, а вот ПРАВИЛО ПРОВЕРКИ — своё, см. `internal_auth`.
"""

from __future__ import annotations


def internal_auth(authorization: str | None) -> None:
    """Проверить bearer для внутренних ручек сайдкара.

    ⚠️ ПОЧЕМУ НЕ ПРОВЕРКОЙ ШЛЮЗА `/v1`, хотя ключ тот же. У неё два свойства, верных для
    `/v1` и разрушительных для всего остального:

    1. **Пустой ключ = пропустить всех** (dev-режим). Именно так `/run` — ручка с полным
       пользовательским контекстом и биллингом — оказалась открытой, а `/providers/keys`
       позволяла любому из внутренней сети ПОДМЕНИТЬ платформе ключи провайдеров.
       Открытая дверь по умолчанию не должна выглядеть рабочей конфигурацией:
       `.env.example` ключ поставляет, поэтому отказ никого не ломает, а недонастройку
       делает заметной сразу, а не после инцидента.
    2. **404 при `llm_gateway_enabled=false`.** Для `/v1` это правда — шлюза нет. Для
       остальных ручек это означало бы, что выключение ЧУЖОЙ функции гасит основную
       работу сервиса, причём кодом «не найдено», который вызывающий читает как «такой
       ручки не существует», а не как «мне не открыли».
    """
    from fastapi import HTTPException

    from service.settings import config

    key = (getattr(config.agents, "llm_gateway_api_key", "") or "").strip()
    if not key:
        raise HTTPException(
            status_code=503,
            detail="internal api key not configured (AGENTS__LLM_GATEWAY_API_KEY)",
        )
    token = (authorization or "").removeprefix("Bearer ").strip()
    if token != key:
        raise HTTPException(status_code=401, detail="invalid internal api key")
