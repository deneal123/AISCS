"""Инструмент-пустышка сжигает раунды tool-loop и роняет ответ.

🔴 НАЙДЕНО ЖИВЫМ ПРОГОНОМ, ПОВЕРХ 1712 ЗЕЛЁНЫХ. Сквозной замер: архив `requests`
развёрнут в песочнице, инструменты `ws_*` выданы, вопрос — «покажи код функции
Session.request и объясни построчно». Модель вызвала `fetch_runtime_context` ПЯТЬ РАЗ
подряд, получая по 119 символов, исчерпала `max_turns=4` и вернула человеку:

    «Не удалось довести задачу до ответа за отведённое число шагов с инструментами.»

Пять вызовов LLM с полным промптом — и НУЛЕВОЙ результат. Инструмент отдавал `timestamp`,
`user_id`, `thread_id`, `input_type`: применить их модели нечем, а называлось это
«получить системный контекст текущего запроса» — ровно то, что модель ищет, когда её
спрашивают про приложенные файлы. Ловушка была ПЕРВОЙ в списке инструментов.

⚠️ ЧЕМУ ЭТО УЧИТ ШИРЕ. Раунды tool-loop — исчерпаемый ресурс (`max_turns=4`, и это не
скупость: каждый раунд переотправляет весь растущий диалог). Значит инструмент, который
не может продвинуть задачу, не просто бесполезен — он ОТНИМАЕТ шаги у тех, что могут.
Поэтому проверяем не «нет ли конкретного имени», а свойство: каждый выдаваемый модели
инструмент обязан приносить данные, которых в промпте нет.
"""

from __future__ import annotations

from service.domain.tools.function_tools import DEFAULT_FUNCTION_TOOLS

_NAMES = {tool.name for tool in DEFAULT_FUNCTION_TOOLS}


def test_the_decoy_is_gone():
    """🔴 ГЛАВНОЕ. Возврат этого инструмента вернул бы и «не удалось довести до ответа»."""
    assert "fetch_runtime_context" not in _NAMES, (
        "инструмент-пустышка снова выдаётся модели: он отдаёт служебные поля, применить "
        "которые нечем, и в живом прогоне сжёг все четыре раунда tool-loop"
    )


def test_no_tool_promises_the_request_context():
    """⚠️ ПРАВИЛО, А НЕ ЗАПРЕТ ИМЕНИ. Дело было не в имени, а в ОБЕЩАНИИ: описание «получить
    контекст текущего запроса» модель читает как «здесь лежат приложенные файлы». Любой
    новый инструмент с такой формулировкой воспроизведёт ту же петлю.
    """
    suspicious = [
        tool.name
        for tool in DEFAULT_FUNCTION_TOOLS
        if "контекст" in (tool.description or "").lower()
        and "запрос" in (tool.description or "").lower()
    ]

    assert not suspicious, (
        f"инструмент обещает «контекст запроса» и уведёт модель за вложениями: {suspicious}"
    )


def test_the_offered_set_stays_small():
    """⚠️ Схемы инструментов стоят токенов В КАЖДОМ запросе, а раунды ограничены четырьмя.
    Набор, растущий без счёта, отнимает шаги у того, что нужно прямо сейчас.

    Потолок мягкий и служит поводом задуматься, а не запретом: если инструмент нужен,
    поднять число можно — вместе с ответом на вопрос, чьи раунды он забирает.
    """
    # S19 adds two capability-gated issue tools.  A workspace run can therefore
    # have 16 candidates; S11's disclosure controller, rather than a stale
    # global cap, keeps the offered schema subset bounded at that point.
    assert len(_NAMES) <= 16, (
        f"инструментов {len(_NAMES)}: выдача должна идти через tier-disclosure, а не расти без счёта"
    )


def test_the_tools_that_remain_bring_something_new():
    """Оставшиеся выдают то, чего в промпте нет: страницу из сети, файл из песочницы,
    таблицу, фрагмент графа, кадры ролика. Это и есть признак осмысленного инструмента."""
    assert "fetch_url" in _NAMES
    assert {"ws_read", "ws_list", "ws_grep"} <= _NAMES
    assert "search_knowledge_graph" in _NAMES
