"""Базовый промпт называет заголовки, которые сборщик контекста РЕАЛЬНО выдаёт.

🔴 ЧТО БЫЛО. `GENERAL_PROMPT` учил модель: «блок „## Контекст из загруженного файла“
означает, что файл УЖЕ приложен — НИКОГДА не проси его заново». Такого заголовка сборщик
контекста не выдаёт уже давно: настоящий — «## Вложения текущей задачи». Правило было
привязано к строке, которую модель не видит ни разу, и не действовало ВООБСЕ.

Отказ этого рода не виден ничем: промпт синтаксически безупречен, тесты зелены, модель
отвечает. Проявляется он только как «агент снова просит приложить файл» — то есть как
жалоба человека, у которого файл приложен.

⚠️ Класс общий: ДВА МЕСТА, НАЗЫВАЮЩИЕ ОДНО И ТО ЖЕ, однажды расходятся. Лечение —
подстановка из источника, а страж следит, что подстановка не выродилась обратно в литерал.
"""

from __future__ import annotations

from service.domain.pipeline.context_assembler import SECTION_TITLES
from service.domain.subagents.general import GENERAL_PROMPT


def test_the_attachment_section_is_named_as_it_is_rendered():
    """🔴 ГЛАВНОЕ. Заголовок в правиле совпадает с тем, что увидит модель."""
    assert SECTION_TITLES["files"] in GENERAL_PROMPT, (
        "правило про вложение названо заголовком, которого сборщик контекста не выдаёт — "
        "модель не сопоставит его ни с чем и снова попросит приложить файл"
    )


def test_no_stale_section_name_survives():
    """⚠️ Проверяем И отсутствие мёртвого имени: подстановка могла бы приписаться РЯДОМ с
    прежним литералом, и тогда промпт называл бы два заголовка, из которых один не бывает."""
    assert "Контекст из загруженного файла" not in GENERAL_PROMPT


def test_the_substitution_actually_happened():
    """🔴 Незаполненная подстановка уехала бы модели дословно — `{files_section}` в тексте
    промпта хуже неверного заголовка: он выглядит как сбой шаблонизатора."""
    assert "{" not in GENERAL_PROMPT and "}" not in GENERAL_PROMPT


def test_a_missing_attachment_block_is_not_silence():
    """⚠️ Обратный случай той же жалобы. Блока нет, а человек говорит «файл приложен» —
    значит содержимое не доехало либо читается инструментом. Выдуманный пересказ здесь
    ХУЖЕ отказа: именно он и пришёл человеку вместо разбора его архива.
    """
    # ⚠️ Переносы строк сминаем: промпт свёрстан по ширине, и правило не должно зависеть
    # от того, где оказался разрыв. Первая редакция стража искала фразу дословно и краснела
    # на переносе — то есть проверяла вёрстку вместо смысла.
    flat = " ".join(GENERAL_PROMPT.lower().split())

    assert "не выдумывай содержимое" in flat, (
        "промпт не запрещает выдумывать содержимое отсутствующего вложения"
    )
    assert "не доехало" in flat, "случай «файл приложен, а блока нет» промптом не описан"


def test_every_named_section_exists_in_the_registry():
    """⚠️ Правило шире одного заголовка: любой «## …», названный базовым промптом, обязан
    быть настоящей секцией. Иначе завтра то же самое случится с другой.

    ⚠️ Собственные заголовки промпта («## Специализация» приписывается личностью) не
    считаются — берём только те, что промпт называет КАК БЛОК КОНТЕКСТА, в кавычках-ёлочках.
    """
    import re

    quoted = set(re.findall(r"«(##[^»]+)»", GENERAL_PROMPT))
    known = set(SECTION_TITLES.values())

    assert quoted, "страж ничего не нашёл — формат ссылки на секцию изменился, проверять нечего"
    assert quoted <= known, f"промпт ссылается на несуществующие секции: {sorted(quoted - known)}"
