"""Генерируемый промпт оркестратора сверяется с золотым файлом ПОБАЙТОВО.

⚠️ ЗАЧЕМ ИМЕННО ПОБАЙТОВО. Промпт — это данные, а не код: лишний пробел, переставленная
строка или изменённый порядок маршрутов меняют поведение модели ровно так же, как правка
логики. Когда `AUTO_PROMPT` перестал быть литералом и стал собираться из спек, единственным
способом доказать, что рефакторинг ничего не пере-настроил, был снимок прежнего текста.

Золотой файл снят с константы ДО перевода на генерацию. Если проверка покраснела — это не
«тест устарел»: кто-то изменил промпт. Обновлять файл можно, только когда изменение
намеренное, и тогда diff в ревью показывает ровно то, что увидит модель.
"""

from __future__ import annotations

import pathlib

GOLDEN = pathlib.Path(__file__).parent / "golden" / "auto_prompt.txt"


def test_auto_prompt_matches_the_golden_snapshot():
    from service.domain.routing.auto_prompt import auto_prompt

    assert auto_prompt() == GOLDEN.read_text(encoding="utf-8")


def test_every_offered_route_is_explained():
    """🔴 Маршрут в JSON-перечислении обязан иметь описание в блоке маршрутов.

    Разойдись эти два рендера — модель получит имя, которое ей нечем истолковать: назвать
    маршрут она сможет, а понять, когда его выбирать, — нет. Ровно так и случилось с первой
    объявленной цепочкой: она попала в перечисление, описания не получила и не выбиралась
    НИ РАЗУ. Поймано живым прогоном, а не тестом, — поэтому тест теперь есть.
    """
    from service.domain.capabilities import render_auto_route_enum, render_auto_routes

    block = render_auto_routes()
    missing = [name for name in render_auto_route_enum().split("|") if f"- {name} — " not in block]

    assert not missing, f"маршруты предложены модели без объяснения: {missing}"
